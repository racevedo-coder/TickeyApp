   private String validarLogin(String correo, String clave) {
    String sql = "SELECT u.id_usuario, u.correo, r.nombre_rol FROM usuario u "
               + "JOIN rol r ON u.id_rol = r.id_rol "
               + "WHERE u.correo = ? AND u.contrasena = SHA2(?, 256) ";

    try (PreparedStatement ps = conexion.getInstancia().getConexion().prepareStatement(sql)) {
        ps.setString(1, correo);
        ps.setString(2, clave);

        try (ResultSet rs = ps.executeQuery()) {
            if (rs.next()) {
                Sesion.idUsuario = rs.getInt("id_usuario");
                Sesion.correo = rs.getString("correo");
                Sesion.rol = rs.getString("nombre_rol");
                return Sesion.rol;
            }
        }
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }
    return null;
}
    
    
    


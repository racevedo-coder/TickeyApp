    private void ponerImagen(javax.swing.JLabel lbl, String ruta, int ancho, int alto) {
    if (ruta == null || ruta.isEmpty()) {
        return;
    }
    java.io.File archivo = new java.io.File(ruta);
    if (archivo.exists()) {
        java.awt.Image img = new javax.swing.ImageIcon(archivo.getAbsolutePath()).getImage()
                .getScaledInstance(ancho, alto, java.awt.Image.SCALE_SMOOTH);
        lbl.setIcon(new javax.swing.ImageIcon(img));
    }
}
    
    private void cargarDestacados() {
    javax.swing.JPanel[] tarjetas = {pnlTarjeta1, pnlTarjeta2, pnlTarjeta3};
    javax.swing.JLabel[] imagenes = {lblImg1, lblImg2, lblImg3};
    javax.swing.JLabel[] fechas   = {lblFecha1, lblFecha2, lblFecha3};
    javax.swing.JLabel[] nombres  = {lblNombre1, lblNombre2, lblNombre3};
    javax.swing.JLabel[] lugares  = {lblLugar1, lblLugar2, lblLugar3};

    java.text.SimpleDateFormat formato =
            new java.text.SimpleDateFormat("d MMM", new java.util.Locale("es", "CO"));

    int i = 0;
    try (CallableStatement cs = conexion.getInstancia().getConexion()
            .prepareCall("{CALL sp_eventos_destacados()}");
         ResultSet rs = cs.executeQuery()) {

        while (rs.next() && i < 3) {
            nombres[i].setText(rs.getString("nombre"));
            lugares[i].setText("<html>" + rs.getString("lugar") + "</html>");
            fechas[i].setText(formato.format(rs.getDate("fecha")));
            ponerImagen(imagenes[i], rs.getString("imagen"), 175, 120);
            i++;
        }
    } catch (SQLException e) {
      JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
     }
    

    for (int j = i; j < 3; j++) {
        tarjetas[j].setVisible(false);
    }
}
  
    private void cargarPromocion() {
    String sql = "SELECT porcentaje, cant_min FROM descuento "
               + "WHERE CURDATE() BETWEEN fecha_inicio AND fecha_fin "
               + "ORDER BY porcentaje DESC, cant_min ASC";

    avisos.clear();
    try (PreparedStatement ps = conexion.getInstancia().getConexion().prepareStatement(sql);
         ResultSet rs = ps.executeQuery()) {

        while (rs.next()) {
            String pct = rs.getBigDecimal("porcentaje").stripTrailingZeros().toPlainString();
            int cantMin = rs.getInt("cant_min");
            if (cantMin > 1) {
                avisos.add("Obtén descuento del " + pct + "% por la compra de "
                        + cantMin + " boletas o más. ¡Aprovecha ahora!");
            } else {
                avisos.add("¡Descuento del " + pct + "% vigente! ¡Aprovecha ahora!");
            }
        }
    } catch (SQLException e) {
        logger.log(java.util.logging.Level.WARNING, "No se pudo cargar el descuento", e);
    }

    indiceAviso = 0;
    if (avisos.isEmpty()) {
        lblAvisoD.setVisible(false);
    } else {
        lblAvisoD.setText(avisos.get(0));
        lblAvisoD.setVisible(true);
    }
}

private void iniciarRotacionAvisos() {
    // Rota el texto cada 5 segundos
    timerAviso = new javax.swing.Timer(5_000, e -> {
        if (avisos.size() > 1) {
            indiceAviso = (indiceAviso + 1) % avisos.size();
            lblAvisoD.setText(avisos.get(indiceAviso));
        }
    });
    timerAviso.start();

    // Vuelve a consultar la base cada minuto (por si uno venció o empezó otro)
    new javax.swing.Timer(60_000, e -> cargarPromocion()).start();
}
   

